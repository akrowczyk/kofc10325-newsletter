// Generates src/lib/exportAssets.generated.ts from the canonical newsletter
// styles, fonts, and emblem, so the self-contained static export (for hosting
// on Hostinger) always matches the app. Runs as part of `npm run dev` / `build`.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p));

const css = read("src/components/newsletter.css").toString("utf8");
const emblem = read("assets/emblem-export.png").toString("base64");

const fonts = [
  { file: "assets/fonts/robotoserif.woff2", family: "Roboto Serif", style: "normal", weight: "500 700", fmt: "woff2" },
  { file: "assets/fonts/robotoserif-i.woff2", family: "Roboto Serif", style: "italic", weight: "500", fmt: "woff2" },
  { file: "assets/fonts/roboto.woff2", family: "Roboto", style: "normal", weight: "400 700", fmt: "woff2" },
  { file: "assets/fonts/robotocondensed.woff", family: "Roboto Condensed", style: "normal", weight: "700", fmt: "woff" },
];

const fontFace = fonts
  .map((f) => {
    const b64 = read(f.file).toString("base64");
    const mime = f.fmt === "woff2" ? "font/woff2" : "font/woff";
    return `@font-face{font-family:'${f.family}';font-style:${f.style};font-weight:${f.weight};font-display:swap;src:url(data:${mime};base64,${b64}) format('${f.fmt}');}`;
  })
  .join("\n");

const emblemUri = `data:image/png;base64,${emblem}`;

const out = `// AUTO-GENERATED by scripts/gen-export-assets.mjs — do not edit by hand.
/* eslint-disable */
export const NEWSLETTER_CSS = ${JSON.stringify(css)};
export const FONT_FACE_CSS = ${JSON.stringify(fontFace)};
export const EMBLEM_DATA_URI = ${JSON.stringify(emblemUri)};
`;

writeFileSync(join(root, "src/lib/exportAssets.generated.ts"), out);
console.log(
  `gen-export-assets: wrote src/lib/exportAssets.generated.ts (css ${css.length}b, fonts ${fontFace.length}b, emblem ${emblemUri.length}b)`,
);
